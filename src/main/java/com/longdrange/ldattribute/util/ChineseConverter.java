    private static void load(String data) {
        if (data == null) return;
        for (int i = 0; i + 1 < data.length(); i += 2) {
            char tw = data.charAt(i);
            char cn = data.charAt(i + 1);
            if (tw == cn) continue;
            T2S.put(tw, cn);
            if (!S2T.containsKey(cn)) S2T.put(cn, tw);
        }
    }

    public static String toSimplified(String s) {
        if (s == null || s.isEmpty()) return s;
        StringBuilder sb = new StringBuilder(s.length());
        for (int i = 0; i < s.length(); i++) {
            Character c = T2S.get(s.charAt(i));
            sb.append(c == null ? s.charAt(i) : c);
        }
        return sb.toString();
    }

    public static String toTraditional(String s) {
        if (s == null || s.isEmpty()) return s;
        StringBuilder sb = new StringBuilder(s.length());
        for (int i = 0; i < s.length(); i++) {
            Character c = S2T.get(s.charAt(i));
            sb.append(c == null ? s.charAt(i) : c);
        }
        return sb.toString();
    }

    public static String normalize(String s) { return toSimplified(s); }

    public static boolean equals(String a, String b) {
        if (a == null || b == null) return a == b;
        return normalize(a).equalsIgnoreCase(normalize(b));
    }

    public static boolean contains(String text, String pattern) {
        if (text == null || pattern == null) return false;
        return normalize(text).contains(normalize(pattern));
    }

    public static boolean startsWith(String text, String prefix) {
        if (text == null || prefix == null) return false;
        return normalize(text).startsWith(normalize(prefix));
    }
